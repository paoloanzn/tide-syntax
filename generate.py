#!/usr/bin/env python3
"""Generate editor syntax files for Tide from syntax.yaml.

Outputs:
  vscode/package.json                    extension manifest
  vscode/language-configuration.json     comments, brackets, auto-closing pairs
  vscode/syntaxes/tide.tmLanguage.json   TextMate grammar
  vim/ftdetect/tide.vim                  filetype detection
  vim/ftplugin/tide.vim                  comment settings
  vim/syntax/tide.vim                    syntax definition

Both grammars are emitted from one ordered list of rules (`rules()`), highest
priority first. The two engines resolve ties at the same start column in
opposite ways: TextMate tries patterns in list order and the first match wins,
Vim lets the item defined last win. So the TextMate grammar is emitted in rule
order and the Vim syntax file in reverse.

Usage: python3 generate.py [--check]
  --check  exit 1 if any generated file is missing or out of date
"""

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
SPEC_PATH = ROOT / "syntax.yaml"
HEADER = "Generated by generate.py from syntax.yaml. Do not edit."


# ------------------------------------------------------------- spec model --

def load_spec():
    spec = yaml.safe_load(SPEC_PATH.read_text())
    classes = spec["classes"]

    def check_class(name, where):
        if name not in classes:
            sys.exit(f"syntax.yaml: unknown class '{name}' in {where}")

    for path, value in _walk(spec):
        if path and path[-1] in ("class", "invalid_class", "accessor_class"):
            check_class(value, ".".join(map(str, path)))
    return spec


def _walk(node, path=()):
    if isinstance(node, dict):
        for k, v in node.items():
            yield from _walk(v, path + (k,))
    elif isinstance(node, list):
        for i, v in enumerate(node):
            yield from _walk(v, path + (i,))
    else:
        yield path, node


def keyword_class(spec, word):
    for group in spec["keywords"]:
        if word in group["words"]:
            return group["class"]
    sys.exit(f"syntax.yaml: declaration keyword '{word}' is not in any keyword group")


def by_length(words):
    return sorted(words, key=lambda w: (-len(w), w))


def symbol_buckets(groups):
    """Split symbol groups into (class, symbols) buckets, longest symbols first,
    so that the first matching bucket always takes the longest operator."""
    buckets = []
    lengths = sorted({len(s) for g in groups for s in g["symbols"]}, reverse=True)
    for n in lengths:
        for g in groups:
            syms = [s for s in g["symbols"] if len(s) == n]
            if syms:
                buckets.append((g["class"], syms))
    return buckets


def symbol_class(spec, symbol):
    for g in spec["operators"] + spec["punctuation"]:
        if symbol in g["symbols"]:
            return g["class"]
    sys.exit(f"syntax.yaml: symbol '{symbol}' is not in any operator or punctuation group")


def assignment_symbols(spec):
    cls = spec["fields"].get("operators_class", "operator_assignment")
    return [s for g in spec["operators"] if g["class"] == cls for s in g["symbols"]]


def rules(spec):
    """Engine-neutral rules in priority order (highest first)."""
    out = [
        {"kind": "block_comment"},
        {"kind": "line_comment"},
        {"kind": "string"},
        {"kind": "type_annotation"},
        {"kind": "field"},
        {"kind": "member"},
    ]
    out += [{"kind": "declaration", **d} for d in spec["declarations"]]
    out += [
        {"kind": "number", "which": "float"},
        {"kind": "number", "which": "integer"},
        {"kind": "words", "class": spec["builtins"]["class"], "words": spec["builtins"]["words"], "call": True},
    ]
    out += [{"kind": "words", "class": g["class"], "words": g["words"], "call": False} for g in spec["keywords"]]
    out += [
        {"kind": "words", "class": spec["types"]["class"], "words": spec["types"]["words"], "call": False},
        {"kind": "call"},
    ]
    out += [{"kind": "symbols", "class": c, "symbols": s} for c, s in symbol_buckets(spec["operators"])]
    out += [{"kind": "symbols", "class": c, "symbols": s} for c, s in symbol_buckets(spec["punctuation"])]
    return out


# ---------------------------------------------------------------- TextMate --

def onig_escape(text):
    return re.sub(r"([.^$|?*+()\[\]{}\\/-])", r"\\\1", text)


def onig_class_escape(chars):
    return "".join("\\" + c if c in "\\]^-[" else c for c in chars)


def textmate(spec):
    lang = spec["language"]["id"]
    ident = spec["identifier"]

    def scope(cls):
        return f"{spec['classes'][cls]['scope']}.{lang}"

    def words_re(words):
        return r"\b(?:" + "|".join(onig_escape(w) for w in by_length(words)) + r")\b"

    todo = spec["comments"]["todo"]
    esc = spec["string"]["escapes"]
    units = spec["numbers"]["units"]
    unit_re = r"(?:\s*(" + "|".join(by_length(units["words"])) + r")\b)?"
    assign_re = "|".join(onig_escape(s) for s in by_length(assignment_symbols(spec)))

    repository = {
        "todo": {"name": scope(todo["class"]), "match": words_re(todo["words"])},
        "escapes": {"patterns": [
            {"name": scope(esc["class"]),
             "match": r"\\(?:[" + onig_class_escape(esc["chars"]) + "]"
                      + (f"|u[0-9A-Fa-f]{{{esc['unicode_hex_digits']}}}" if esc.get("unicode_hex_digits") else "")
                      + ")"},
            {"name": scope(esc["invalid_class"]), "match": r"\\."},
        ]},
    }
    patterns = []

    for rule in rules(spec):
        kind = rule["kind"]
        if kind == "block_comment":
            c = spec["comments"]["block"]
            p = {"name": scope(c["class"]), "begin": onig_escape(c["start"]), "end": onig_escape(c["end"]),
                 "patterns": [{"include": "#todo"}]}
        elif kind == "line_comment":
            c = spec["comments"]["line"]
            p = {"name": scope(c["class"]), "begin": onig_escape(c["start"]), "end": "$",
                 "patterns": [{"include": "#todo"}]}
        elif kind == "string":
            s = spec["string"]
            d = onig_escape(s["delimiter"])
            p = {"name": scope(s["class"]), "begin": d, "end": d if s.get("multiline") else f"{d}|$",
                 "patterns": [{"include": "#escapes"}]}
        elif kind == "type_annotation":
            t = spec["types"]
            types = "|".join(onig_escape(w) for w in by_length(t["words"]))
            p = {"match": rf"({onig_escape(t['annotation_prefix'])})\s*\b({types})\b",
                 "captures": {"1": {"name": scope(symbol_class(spec, t["annotation_prefix"]))},
                              "2": {"name": scope(t["class"])}}}
        elif kind == "field":
            p = {"match": rf"\b({ident})\b(?=\s*(?:{assign_re})(?!=))",
                 "captures": {"1": {"name": scope(spec["fields"]["class"])}}}
        elif kind == "member":
            m = spec["members"]
            p = {"match": rf"(\.)({ident})\b",
                 "captures": {"1": {"name": scope(m["accessor_class"])}, "2": {"name": scope(m["class"])}}}
        elif kind == "declaration":
            guard = r"(?!\s*[(.])" if rule.get("guard_expression", True) else ""
            p = {"match": rf"\b({onig_escape(rule['keyword'])})\s+({ident})\b{guard}",
                 "captures": {"1": {"name": scope(keyword_class(spec, rule["keyword"]))},
                              "2": {"name": scope(rule["class"])}}}
        elif kind == "number":
            num = r"\d+\.\d+" if rule["which"] == "float" else r"\d+"
            p = {"match": rf"\b({num}){unit_re}",
                 "captures": {"1": {"name": scope(spec["numbers"][rule["which"]]["class"])},
                              "2": {"name": scope(units["class"])}}}
        elif kind == "words":
            p = {"name": scope(rule["class"]), "match": words_re(rule["words"]) + (r"(?=\s*\()" if rule["call"] else "")}
        elif kind == "call":
            p = {"match": rf"\b({ident})(?=\s*\()",
                 "captures": {"1": {"name": scope(spec["calls"]["class"])}}}
        elif kind == "symbols":
            p = {"name": scope(rule["class"]), "match": "|".join(onig_escape(s) for s in rule["symbols"])}
        else:
            raise AssertionError(kind)
        patterns.append(p)

    return {
        "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
        "comment": HEADER,
        "name": spec["language"]["name"],
        "scopeName": spec["language"]["scope"],
        "fileTypes": spec["language"]["extensions"],
        "patterns": patterns,
        "repository": repository,
    }


def language_configuration(spec):
    c = spec["comments"]
    d = spec["string"]["delimiter"]
    pairs = [{"open": o, "close": cl} for o, cl in spec["brackets"]]
    return {
        "comments": {"lineComment": c["line"]["start"], "blockComment": [c["block"]["start"], c["block"]["end"]]},
        "brackets": spec["brackets"],
        "autoClosingPairs": pairs + [{"open": d, "close": d, "notIn": ["string", "comment"]}],
        "surroundingPairs": spec["brackets"] + [[d, d]],
    }


def package_json(spec):
    pkg, lang = spec["package"], spec["language"]
    return {
        "name": pkg["name"],
        "displayName": pkg["display_name"],
        "description": pkg["description"],
        "version": pkg["version"],
        "publisher": pkg["publisher"],
        "engines": {"vscode": pkg["vscode_engine"]},
        "categories": ["Programming Languages"],
        "contributes": {
            "languages": [{
                "id": lang["id"],
                "aliases": [lang["name"], lang["id"]],
                "extensions": ["." + e for e in lang["extensions"]],
                "configuration": "./language-configuration.json",
            }],
            "grammars": [{
                "language": lang["id"],
                "scopeName": lang["scope"],
                "path": f"./syntaxes/{lang['id']}.tmLanguage.json",
            }],
        },
    }


# --------------------------------------------------------------------- Vim --

VIM_MAGIC = set("\\.*[]~^$")


def vim_escape(text):
    return "".join("\\" + c if c in VIM_MAGIC else c for c in text)


def vim_pattern(pattern):
    """Wrap a Vim regex in a delimiter that does not occur in it."""
    for delim in "/+#!@%,|":
        if delim not in pattern:
            return f"{delim}{pattern}{delim}"
    raise ValueError(f"no free delimiter for {pattern!r}")


def vim_group(spec, cls):
    return spec["language"]["id"] + "".join(part.capitalize() for part in cls.split("_"))


def vim_syntax(spec):
    lang = spec["language"]["id"]
    ident = spec["identifier"]
    g = lambda cls: vim_group(spec, cls)

    def words_re(words):
        return r"\<\%(" + r"\|".join(vim_escape(w) for w in by_length(words)) + r"\)\>"

    todo = spec["comments"]["todo"]
    esc = spec["string"]["escapes"]
    units = spec["numbers"]["units"]
    assign_re = r"\|".join(vim_escape(s) for s in by_length(assignment_symbols(spec)))
    hl_classes = {todo["class"], esc["class"], esc["invalid_class"], units["class"]}

    # Name groups are shared by every declaration of the same class, so their
    # guard setting must agree.
    name_guard = {}
    for d in spec["declarations"]:
        guard = d.get("guard_expression", True)
        if name_guard.setdefault(d["class"], guard) != guard:
            sys.exit(f"syntax.yaml: declarations of class '{d['class']}' disagree on guard_expression")

    items = []  # each entry: (vim command, class it highlights)
    for rule in rules(spec):
        kind = rule["kind"]
        cmds = []
        if kind == "block_comment":
            c = spec["comments"]["block"]
            cmds.append((f"syntax region {g(c['class'])} start={vim_pattern(vim_escape(c['start']))} "
                         f"end={vim_pattern(vim_escape(c['end']))} contains={g(todo['class'])}", c["class"]))
        elif kind == "line_comment":
            c = spec["comments"]["line"]
            cmds.append((f"syntax match {g(c['class'])} {vim_pattern(vim_escape(c['start']) + '.*$')} "
                         f"contains={g(todo['class'])}", c["class"]))
        elif kind == "string":
            s = spec["string"]
            d = vim_escape(s["delimiter"])
            end = d if s.get("multiline") else d + r"\|$"
            skip = vim_pattern(r"\\\\\|\\" + d)
            cmds.append((f"syntax region {g(s['class'])} start={vim_pattern(d)} skip={skip} "
                         f"end={vim_pattern(end)} contains={g(esc['class'])},{g(esc['invalid_class'])}", s["class"]))
        elif kind == "type_annotation":
            t = spec["types"]
            pat = rf"\%({vim_escape(t['annotation_prefix'])}\s*\)\@20<=" + words_re(t["words"])
            cmds.append((f"syntax match {g(t['class'])} {vim_pattern(pat)}", t["class"]))
        elif kind == "field":
            pat = rf"\<{ident}\>\ze\s*\%({assign_re}\)=\@!"
            cmds.append((f"syntax match {g(spec['fields']['class'])} {vim_pattern(pat)}", spec["fields"]["class"]))
        elif kind == "member":
            pat = rf"\.\@1<!\.\zs{ident}\>"
            cmds.append((f"syntax match {g(spec['members']['class'])} {vim_pattern(pat)}", spec["members"]["class"]))
        elif kind == "declaration":
            kw_cls = keyword_class(spec, rule["keyword"])
            cmds.append((f"syntax match {g(kw_cls)} {vim_pattern(words_re([rule['keyword']]))} "
                         f"nextgroup={g(rule['class'])} skipwhite", kw_cls))
        elif kind == "number":
            num = r"\<\d\+\.\d\+" if rule["which"] == "float" else r"\<\d\+"
            cls = spec["numbers"][rule["which"]]["class"]
            cmds.append((f"syntax match {g(cls)} {vim_pattern(num)} nextgroup={g(units['class'])} skipwhite", cls))
        elif kind == "words":
            pat = words_re(rule["words"]) + (r"\ze\s*(" if rule["call"] else "")
            cmds.append((f"syntax match {g(rule['class'])} {vim_pattern(pat)}", rule["class"]))
        elif kind == "call":
            pat = rf"\<{ident}\>\ze\s*("
            cmds.append((f"syntax match {g(spec['calls']['class'])} {vim_pattern(pat)}", spec["calls"]["class"]))
        elif kind == "symbols":
            pat = r"\|".join(vim_escape(s) for s in rule["symbols"])
            cmds.append((f"syntax match {g(rule['class'])} {vim_pattern(pat)}", rule["class"]))
        else:
            raise AssertionError(kind)
        items.append(cmds)

    invalid_escape_re = vim_pattern(r"\\.")
    unit_re = vim_pattern(r"\%(" + r"\|".join(by_length(units["words"])) + r"\)\>")
    lines = [
        '" Vim syntax file',
        f'" Language: {spec["language"]["name"]}',
        f'" {HEADER}',
        "",
        'if exists("b:current_syntax")',
        "  finish",
        "endif",
        "",
        "let s:cpo_save = &cpo",
        "set cpo&vim",
        "",
        "syntax case match",
        "",
        '" Contained items.',
        f"syntax keyword {g(todo['class'])} {' '.join(todo['words'])} contained",
        f"syntax match {g(esc['invalid_class'])} {invalid_escape_re} contained",
        f"syntax match {g(esc['class'])} "
        + vim_pattern(r"\\\%([" + "".join("\\" + c if c in "\\]^-" else c for c in esc["chars"]) + r"]"
                      + (rf"\|u\x\{{{esc['unicode_hex_digits']}}}" if esc.get("unicode_hex_digits") else "")
                      + r"\)")
        + " contained",
        f"syntax match {g(units['class'])} {unit_re} contained",
    ]
    for cls, guard in name_guard.items():
        guard_re = r"\%(\s*[(.]\)\@!" if guard else ""
        name_re = vim_pattern(ident + r"\>" + guard_re)
        lines.append(f"syntax match {g(cls)} {name_re} contained")
        hl_classes.add(cls)

    lines += ["", '" Top-level items, lowest priority first (in Vim the last definition wins).']
    for cmds in reversed(items):
        for cmd, cls in cmds:
            if spec["classes"][cls]["vim"] is None:
                continue
            lines.append(cmd)
            hl_classes.add(cls)

    lines += ["", "syntax sync minlines=200", ""]
    for cls in spec["classes"]:
        target = spec["classes"][cls]["vim"]
        if cls in hl_classes and target:
            lines.append(f"highlight default link {g(cls)} {target}")

    lines += ["", f'let b:current_syntax = "{lang}"', "", "let &cpo = s:cpo_save", "unlet s:cpo_save", ""]
    return "\n".join(lines)


def vim_ftdetect(spec):
    lang = spec["language"]
    globs = ",".join(f"*.{e}" for e in lang["extensions"])
    return f'" {HEADER}\nautocmd BufRead,BufNewFile {globs} setfiletype {lang["id"]}\n'


def vim_ftplugin(spec):
    c = spec["comments"]
    line, (start, end) = c["line"]["start"], (c["block"]["start"], c["block"]["end"])
    return "\n".join([
        f'" {HEADER}',
        'if exists("b:did_ftplugin")',
        "  finish",
        "endif",
        "let b:did_ftplugin = 1",
        "",
        f"setlocal commentstring={line}\\ %s",
        f"setlocal comments=s1:{start},mb:*,ex:{end},:{line}",
        "setlocal formatoptions-=t formatoptions+=croql",
        "",
        "let b:undo_ftplugin = 'setlocal commentstring< comments< formatoptions<'",
        "",
    ])


# -------------------------------------------------------------------- main --

def outputs(spec):
    lang = spec["language"]["id"]
    as_json = lambda obj: json.dumps(obj, indent=2, ensure_ascii=False) + "\n"
    return {
        "vscode/package.json": as_json(package_json(spec)),
        "vscode/language-configuration.json": as_json(language_configuration(spec)),
        f"vscode/syntaxes/{lang}.tmLanguage.json": as_json(textmate(spec)),
        f"vim/ftdetect/{lang}.vim": vim_ftdetect(spec),
        f"vim/ftplugin/{lang}.vim": vim_ftplugin(spec),
        f"vim/syntax/{lang}.vim": vim_syntax(spec),
    }


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, content in outputs(load_spec()).items():
        path = ROOT / rel
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {rel}")
    if stale:
        print("out of date (run `python3 generate.py`):\n  " + "\n  ".join(stale), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
